#!/usr/bin/env python3
"""run.py -- one ResPlan plan through the whole pipeline.

    python run.py --index 17                    # OFFICIAL mode: stops with a clear error until
                                                # the organisers' node coordinates are available
    python run.py --index 17 --dev-probe-nodes  # DEV ONLY: made-up probe nodes, stamped DEV_ONLY_NOT_OFFICIAL

Steps: load plan -> adapter (metres) -> nodes -> assignment (B) -> hub placement -> routing ->
JSON -> validation -> overlay picture.

Official mode never invents a node. Dev mode writes only into out_dev/, names every file
DEV_ONLY_NOT_OFFICIAL_*, adds a DEV_ONLY_NOT_OFFICIAL key to the JSON and a banner to the picture.
"""
import argparse
import inspect
import json
import os
import pickle
import sys
from collections import Counter

import numpy as np

from panel_routing.contract import Device, PanelAssignment
from panel_routing.output import debug_info, room_name, to_json
from panel_routing.route import make_router, route_all
from panel_routing.validator import validate

MIN_HUB_CLEARANCE_M = 0.5      # official rule: hub >= 0.5 m from walls
HUB_MARGIN_M = 0.05            # keep candidates a little inside the limit
HUB_NODE_GAP_M = 0.5           # assumption: keep a hub off the exact node point (avoids a zero-length ring)
CANDIDATE_STEP_M = 0.25
DEV_STAMP = "DEV_ONLY_NOT_OFFICIAL"


class PipelineError(Exception):
    """A clear, user-facing reason the pipeline cannot continue."""


# ------------------------------------------------------------------ nodes
def official_devices(plan):
    """Official mode: nodes are generated by us (organiser clarification), >= 0.5 m from walls. See nodes.py."""
    if getattr(plan, "free_space", None) is None or not getattr(plan, "geo", None):
        raise PipelineError(
            "node generation not available: the plan has no free-space geometry (it must come from the adapter). "
            "Nothing was fabricated. Re-run with --dev-probe-nodes only for a DEV-ONLY test run.")
    from nodes import NodeGenerationError, generate_nodes
    try:
        devices, report = generate_nodes(plan)
    except NodeGenerationError as e:
        names = [(room_name(r), why) for r, why in e.failures]
        raise PipelineError(f"node generation failed for {names}. No node was forced and no room was dropped; "
                            f"source geometry or the small-room rule needs a team/organiser decision.")
    plan.node_report = report
    return devices


def dev_probe_devices(plan):
    """DEV ONLY. One probe point per eligible room (pole of inaccessibility). Not official nodes."""
    from shapely.ops import polylabel
    devices = []
    for k, room in enumerate(plan.eligible_rooms, start=1):
        # Probe must lie in the part of the room that is routable (inside free_space).
        region = room.polygon.intersection(plan.free_space)
        parts = [g for g in getattr(region, "geoms", [region]) if g.geom_type == "Polygon" and g.area > 1e-6]
        if not parts:
            raise PipelineError(
                f"dev probe: room {room_name(room.id)} has no free space (room lies outside the walkable "
                f"area in the source geometry); cannot place a probe. Source-geometry issue, not routing.")
        p = polylabel(max(parts, key=lambda g: g.area), tolerance=0.05)
        devices.append(Device(k, room.id, (float(p.x), float(p.y))))
    return devices


def attach_devices(plan, devices, source):
    plan.devices = devices
    plan.__post_init__()           # rebuild the id lookups; extra attributes (scale, room_names, geo) are kept
    plan.nodes_source = source


def check_nodes(plan):
    """Refuse to assign or route a plan that has no (or inconsistent) nodes."""
    if not plan.devices:
        raise PipelineError("plan has no devices/nodes: refusing to assign or route an empty plan")
    eligible = {r.id for r in plan.eligible_rooms}
    per_room = Counter(d.room_id for d in plan.devices)
    bad = sorted(room_name(r) for r in eligible if per_room[r] != 1)
    if bad:
        raise PipelineError(f"every eligible room needs exactly one node; problem rooms: {bad}")
    stray = [d.id for d in plan.devices if d.room_id not in eligible]
    if stray:
        raise PipelineError(f"nodes {stray} sit in rooms that are not eligible")


# ------------------------------------------------------------------ assignment and hubs
def normalise(raw):
    """Turn B's output into panel_routing PanelAssignments (B's class may come from another contract copy)."""
    if not isinstance(raw, (list, tuple)) or not raw:
        raise PipelineError(f"assign() must return a non-empty list of assignments, got {type(raw).__name__}")
    out = []
    for i, a in enumerate(raw):
        for attr in ("panel_id", "room_ids", "device_ids"):
            if not hasattr(a, attr):
                raise PipelineError(f"assignment {i} has no '{attr}'; expected PanelAssignment-like objects")
        xy = getattr(a, "panel_xy", None)
        out.append(PanelAssignment(a.panel_id, tuple(xy) if xy is not None else None,
                                   list(a.room_ids), list(a.device_ids), list(getattr(a, "warnings", None) or [])))
    return out


def _inside(hooks, p):
    return bool(np.asarray(hooks["inside"](np.array([p[0]]), np.array([p[1]])))[0])


def hub_ok(plan, a, hooks):
    p = a.panel_xy
    if p is None:
        return False
    in_room = any(hooks["room_contains"](rid, p) for rid in a.room_ids if plan.room_by_id(rid).eligible)
    return bool(in_room and hooks["wall_distance"](p) >= MIN_HUB_CLEARANCE_M - 1e-6 and _inside(hooks, p))


def choose_hub_point(plan, a, hooks):
    """Hub point in an assigned eligible room, >= 0.5 m from walls, near its nodes.

    Cost is a cheap proxy (sum of Manhattan distances to the hub's nodes). Routing-aware
    refinement is a later improvement."""
    nodes = [tuple(plan.device_by_id(d).xy) for d in a.device_ids]
    best = None
    for rid in a.room_ids:
        room = plan.room_by_id(rid)
        if not room.eligible:
            continue
        x0, y0, x1, y1 = room.polygon.bounds
        for x in np.arange(x0, x1 + 1e-9, CANDIDATE_STEP_M):
            for y in np.arange(y0, y1 + 1e-9, CANDIDATE_STEP_M):
                p = (float(x), float(y))
                if not hooks["room_contains"](rid, p):
                    continue
                if hooks["wall_distance"](p) < MIN_HUB_CLEARANCE_M + HUB_MARGIN_M or not _inside(hooks, p):
                    continue
                if any(abs(p[0] - n[0]) + abs(p[1] - n[1]) < HUB_NODE_GAP_M for n in nodes):
                    continue
                cost = sum(abs(p[0] - n[0]) + abs(p[1] - n[1]) for n in nodes)
                if best is None or cost < best[0] - 1e-9:
                    best = (cost, p, rid)
    return best


# ------------------------------------------------------------------ pipeline core (no file or dataset access)
def solve(plan, assign_fn, hooks, router_factory=make_router, step=0.1):
    check_nodes(plan)
    try:
        raw = assign_fn(plan)
    except TypeError as e:
        raise PipelineError(f"assign() could not be called with a Plan: {e}")
    assignments = normalise(raw)

    for a in assignments:
        if not hub_ok(plan, a, hooks):
            best = choose_hub_point(plan, a, hooks)
            if best is None:
                raise PipelineError(f"hub {a.panel_id}: no point >= {MIN_HUB_CLEARANCE_M} m from walls in "
                                    f"rooms {[room_name(r) for r in a.room_ids]}")
            a.warnings.append(f"hub point set by run.py to {best[1]} (assignment gave {a.panel_xy})")
            a.panel_xy = best[1]

    router = router_factory(plan, [a.panel_xy for a in assignments], step=step)
    loops = route_all(plan, assignments, router=router)
    data = to_json(plan, assignments, loops)
    report = validate(data, plan, **hooks)
    return {"assignments": assignments, "loops": loops, "data": data, "report": report}


# ------------------------------------------------------------------ real-data helpers
def make_hooks(plan):
    """Shapely-based hooks for the validator and hub placement (plan must come from the adapter)."""
    from shapely import contains_xy
    from shapely.geometry import Point
    free = plan.free_space
    blocked = plan.geo["walls"].union(plan.geo["windows"])
    return {
        "inside": lambda x, y: contains_xy(free, x, y),
        "wall_distance": lambda p: blocked.distance(Point(p)),
        "room_contains": lambda rid, p: plan.room_by_id(rid).polygon.covers(Point(p)),
    }


def room_shapes(plan):
    shapes, labels = {}, {}
    for r in plan.rooms:
        if r.polygon.geom_type != "Polygon":
            continue
        name = room_name(r.id)
        shapes[name] = list(r.polygon.exterior.coords)
        gid = getattr(plan, "room_names", {}).get(r.id, "")
        labels[name] = f"{name} {gid} {r.area:.1f} m2"
    return shapes, labels


def doors_in_metres(g, geometry):
    out = []
    for gate in g["gates"]:
        if gate.get("usable"):
            c = list(geometry.to_metres(gate["segment"], g["scale"]).coords)
            out.append((tuple(c[0]), tuple(c[-1])))
    return out


def print_summary(plan, result, dev):
    rep, data = result["report"], result["data"]
    m = rep["metrics"] or {}
    print(f"\nplan {plan.plan_id}: {len(plan.rooms)} rooms, {len(plan.devices)} nodes "
          f"({'DEV PROBES, NOT OFFICIAL' if dev else 'official'})")
    print(f"  hubs: {len(data['hubs'])}  (lower bound {rep['hub_lower_bound']})")
    if m:
        print(f"  L={m['L']:.2f} m  X={m['X']}  O={m['O']:.2f} m  B={m['B']}  J={m['J']:.2f}")
    print(f"  valid: {rep['valid']}")
    for v in rep["violations"]:
        print(f"    VIOLATION [{v['rule']}] {v.get('hub') or ''}: {v['message']}")
    if rep["unchecked"]:
        print("  NOT checked:", "; ".join(rep["unchecked"]))
    warns = [w for a in result["assignments"] for w in a.warnings] + [w for l in result["loops"] for w in l.warnings]
    for w in warns:
        print("  warning:", w)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--index", type=int, default=0, help="plan index in ResPlan.pkl")
    ap.add_argument("--pkl", default="ResPlan.pkl")
    ap.add_argument("--dev-probe-nodes", action="store_true",
                    help="DEV ONLY: made-up probe nodes. Output is stamped DEV_ONLY_NOT_OFFICIAL.")
    ap.add_argument("--step", type=float, default=0.1, help="routing grid step in metres")
    args = ap.parse_args()

    sys.path.insert(0, os.getcwd())
    try:
        import adapter
        import assign
        import geometry
        from visualize import draw
        with open(args.pkl, "rb") as f:
            raw = pickle.load(f)[args.index]
        g = geometry.load_plan(raw)
        plan = adapter.make_plan(g)

        dev = args.dev_probe_nodes
        attach_devices(plan, dev_probe_devices(plan) if dev else official_devices(plan),
                       "DEV_PROBE" if dev else "GENERATED_BY_RULE")
        hooks = make_hooks(plan)
        result = solve(plan, assign.assign, hooks, step=args.step)
    except PipelineError as e:
        sys.exit(f"ERROR: {e}")
    except TypeError as e:
        sys.exit(f"ERROR: {e}\n(assign.assign signature: {inspect.signature(assign.assign)})")

    data = result["data"]
    outdir = "out_dev" if dev else "out"
    prefix = f"{DEV_STAMP}_" if dev else ""
    os.makedirs(outdir, exist_ok=True)
    if dev:
        data = {**data, DEV_STAMP: "probe nodes were generated locally for testing; this file must never be submitted"}
    jpath = os.path.join(outdir, f"{prefix}plan_{args.index}.json")
    with open(jpath, "w") as f:
        json.dump(data, f, indent=2)
    shapes, labels = room_shapes(plan)
    ppath = draw(result["data"], shapes, os.path.join(outdir, f"{prefix}plan_{args.index}.png"),
                 doors=doors_in_metres(g, geometry), report=result["report"], room_labels=labels,
                 title=f"ResPlan plan index {args.index} (id {plan.plan_id})",
                 banner=f"{DEV_STAMP}: probe nodes made up for testing, not official" if dev else None)
    print_summary(plan, result, dev)
    print(f"\nwrote {jpath}\nwrote {ppath}")
    sys.exit(0 if result["report"]["valid"] else 1)


if __name__ == "__main__":
    main()
